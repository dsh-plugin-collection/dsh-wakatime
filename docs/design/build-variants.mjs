// Build the dsh-wakatime logo variants from the official marks.
//
// Source of the official paths: docs/design/logo.svg — a pristine copy of the
// pre-redesign assets/logo.svg (official DSH whale, WakaTime ring + W glyph).
//
// Outputs:
//   assets/logo.svg              shipped logo (方案 A · 鲸鱼踏浪)
//   docs/design/logo-new.svg     copy of the shipped logo for local previews
//   docs/design/logo-v2-b.svg    alternate direction (fixed dual-field)
//   docs/design/logo-v2-c.svg    alternate direction (W ring, minimal)
//
// Run: node docs/design/build-variants.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('logo.svg', import.meta.url), 'utf8');
const pick = (re, name) => {
  const m = src.match(re);
  if (!m) throw new Error(`official path not found: ${name}`);
  return m[1];
};
const whale = pick(/d="(M48\.8354[^"]+)"/, 'DSH whale');
const ring  = pick(/d="(M170 20[^"]+)"/, 'WakaTime ring');
const wakaW = pick(/d="(M190\.183[^"]+)"/, 'WakaTime W glyph');

// —— 方案 A · 鲸鱼踏浪(shipped)——
// Refined against the first preview: wave scaled 1.35 → 1.1 so it stays
// secondary, whale raised 40 → 36 and wave dropped 147 → 202, widening the
// waterline gap to ~42px (≈1.3px at 16px render) so the two shapes stay apart.
const finalA = `<!-- dsh-wakatime logo — "whale over the heartbeat wave".
     Whale: official DSH favicon mark, verbatim.
     Wave: official WakaTime W glyph, verbatim, recast as the waterline.
     Generated by docs/design/build-variants.mjs — edit geometry there. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="dsh-wakatime logo">
  <defs>
    <linearGradient id="dshwa-bg" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="#6B83FF"/>
      <stop offset="100%" stop-color="#4053E8"/>
    </linearGradient>
    <radialGradient id="dshwa-sheen" cx="35%" cy="22%" r="80%">
      <stop offset="0%" stop-color="#ffffff" stop-opacity=".14"/>
      <stop offset="55%" stop-color="#ffffff" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <circle cx="256" cy="256" r="240" fill="url(#dshwa-bg)"/>
  <circle cx="256" cy="256" r="240" fill="url(#dshwa-sheen)"/>
  <!-- WakaTime W glyph as the heartbeat wave the whale rides -->
  <g transform="translate(60 202) scale(1.1)">
    <path d="${wakaW}" fill="#ffffff" stroke="#ffffff" stroke-width="10"/>
  </g>
  <!-- DSH whale, dominant -->
  <path d="${whale}" fill="#ffffff" transform="translate(111 36) scale(5.8)"/>
</svg>
`;

// —— 方案 B · 修正双区(alternate)——
const svgB = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img">
  <defs>
    <linearGradient id="steel" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="#6493BC"/>
      <stop offset="100%" stop-color="#395573"/>
    </linearGradient>
    <linearGradient id="indigo" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="#6B83FF"/>
      <stop offset="100%" stop-color="#4053E8"/>
    </linearGradient>
    <clipPath id="disc"><circle cx="256" cy="256" r="240"/></clipPath>
  </defs>
  <circle cx="256" cy="256" r="240" fill="url(#steel)"/>
  <g clip-path="url(#disc)">
    <path d="M0 0 H512 V48 L48 512 H0 Z" fill="url(#indigo)"/>
  </g>
  <path d="${whale}" fill="#ffffff" transform="translate(65 54) scale(5.2)"/>
  <g transform="translate(265 265) scale(0.5)">
    <path d="${ring}" fill="none" stroke="#ffffff" stroke-width="40"/>
    <path d="${wakaW}" fill="#ffffff" stroke="#ffffff" stroke-width="10"/>
  </g>
</svg>
`;

// —— 方案 C · W 环极简(alternate)——
const svgC = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img">
  <defs>
    <linearGradient id="bgc" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="#6B83FF"/>
      <stop offset="100%" stop-color="#4053E8"/>
    </linearGradient>
  </defs>
  <circle cx="256" cy="256" r="240" fill="url(#bgc)"/>
  <g transform="translate(94.5 94.5) scale(0.95)">
    <path d="${ring}" fill="none" stroke="#ffffff" stroke-width="40"/>
    <path d="${wakaW}" fill="#ffffff" stroke="#ffffff" stroke-width="10"/>
  </g>
</svg>
`;

writeFileSync(new URL('../../assets/logo.svg', import.meta.url), finalA);
writeFileSync(new URL('logo-new.svg', import.meta.url), finalA);
writeFileSync(new URL('logo-v2-b.svg', import.meta.url), svgB);
writeFileSync(new URL('logo-v2-c.svg', import.meta.url), svgC);
console.log('wrote assets/logo.svg (A, refined), logo-new.svg, logo-v2-b.svg, logo-v2-c.svg');
